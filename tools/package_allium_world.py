"""Build native Allium world inputs; main.ttw is created by the game harness."""
import json
import shutil
from pathlib import Path
import xml.etree.ElementTree as ET
import numpy as np
from PIL import Image, ImageDraw

ROOT=Path(__file__).resolve().parents[1]
source=ROOT/'artifacts/maps/Allium-v0.1'
out=ROOT/'artifacts/maps/Allium-v0.2'
out.mkdir(parents=True,exist_ok=True)
spec=json.loads((ROOT/'src/Worlds/Allium/layout.json').read_text())
n=json.loads((source/'manifest.json').read_text())['size']
for name in ['dtm.raw','biomes.png']:
    shutil.copyfile(source/name,out/name)
def xml(name,root):
    ET.indent(root)
    ET.ElementTree(root).write(out/name,encoding='utf-8',xml_declaration=True)
info=ET.Element('MapInfo')
for key,value in {'Name':'Allium-v0.2','HeightMapSize':f'{n},{n}','Scale':'1','Modes':'Survival,SurvivalSP,SurvivalMP,Creative','FixedWaterLevel':'false','RandomGeneratedWorld':'false','Description':'Allium terrain exploration alpha'}.items():
    ET.SubElement(info,'property',name=key,value=value)
xml('map_info.xml',info)
height=np.asarray(Image.open(source/'heightmap.png'),dtype=np.float32)/257
water=np.zeros((n,n),dtype=np.uint8)
water[height<49.5]=50
# Narrow water ribbon within the authored river bed; dry route crossings win.
river=np.asarray(Image.open(source/'river-mask.png'))
wet=(river>230)&(height>49.5)
water[wet]=np.ceil(height[wet]+1.2).astype(np.uint8)
route=np.asarray(Image.open(source/'route-mask.png'))
water[route>100]=0
splat4=np.zeros((n,n,4),dtype=np.uint8)
splat4[:,:,2]=water
Image.fromarray(splat4).save(out/'splat4.png')
del splat4,river,wet
# Native decorator maps splat3 green to gravel (POI index 3).
splat3=np.zeros((n,n,4),dtype=np.uint8)
# The graded corridor is broad; draw a separate 8-metre walking road inside it.
road=Image.new('L',(n,n))
d=ImageDraw.Draw(road)
for path in [spec['route'],spec['capital_route']]:
    d.line([(round(x*(n-1)),round(y*(n-1))) for x,y,z in path],fill=255,width=8)
splat3[:,:,1]=np.asarray(road)
Image.fromarray(splat3).save(out/'splat3.png')
del splat3
for name in ['splat1.png','splat2.png']:
    Image.new('RGBA',(n,n),(0,0,0,0)).save(out/name)
radiation=Image.new('RGB',(512,512),'black')
ImageDraw.Draw(radiation).rectangle((0,0,511,511),outline='red',width=8)
radiation.save(out/'radiation.png')
xml('water_info.xml',ET.Element('WaterSources'))
spawn=ET.Element('spawnpoints')
sx,sy,sz=spec['sites'][0]['position']
wx,wz=round((sx-.5)*n),round((.5-sy)*n)
for dx,dz in [(-25,-25),(-15,-25),(-25,-15),(-15,-15)]:
    ET.SubElement(spawn,'spawnpoint',position=f'{wx+dx},{sz+2},{wz+dz}',rotation='0,45,0')
xml('spawnpoints.xml',spawn)
# Trader supplies, shelter and quests are temporary vanilla placeholders.
prefabs=ET.Element('prefabs')
ET.SubElement(prefabs,'decoration',type='model',name='trader_rekt',position=f'{wx+5},{sz},{wz+5}',rotation='0',y_is_groundlevel='true')
xml('prefabs.xml',prefabs)
(out/'BUILD-NOTES.txt').write_text('Allium terrain exploration alpha. Vanilla trader_rekt is a temporary Wayrest supply/quest hub. No custom settlement NPCs or capital structures yet. main.ttw must be generated by Prepare-Allium and the runtime harness before distribution. Water uses splat4 blue-channel height. Existing saves must not be reused after map edits.\n')
print(out)
