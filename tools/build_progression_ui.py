def el(p,tag,**attrs):return E.SubElement(p,tag,{k:str(v) for k,v in attrs.items()})
def save(p,root):p.parent.mkdir(parents=True,exist_ok=True);E.indent(root,space='  ');E.ElementTree(root).write(p,encoding='utf-8',xml_declaration=True)
def label(p,name,x,y,w,h,text,size=18,color='220,225,230',**kw):return el(p,'label',name=name,pos=f'{x},{-y}',width=w,height=h,text=text,font_size=size,color=color,depth=5,justify='left',pivot='topleft',**kw)
def sprite(p,name,x,y,w,h,color,**kw):return el(p,'sprite',name=name,pos=f'{x},{-y}',width=w,height=h,sprite='menu_empty',color=color,depth=1,type='sliced',**kw)
def button(p,name,x,y,w,h,caption,**kw):return el(p,'simplebutton',name=name,pos=f'{x},{-y}',width=w,height=h,caption=caption,font_size=17,depth=4,defaultcolor='38,49,60',hovercolor='67,84,96',bordercolor='70,86,98',**kw)
def player_description(perk):
 text=perk['description']
 for prefix in ['In implementation,','This replaces the former','The fundamental count','Requires a targeted damage modifier;','Exact mapping to the native','Use native head/weak-point metadata']:
  text=re.sub(re.escape(prefix)+r'[^.]*\.?','',text)
 text=text.replace('No immunity, and no claimed reduction of ragdoll physics without implementation.','Does not grant immunity or reduce knockdowns.')
 return ' '.join(text.split())

